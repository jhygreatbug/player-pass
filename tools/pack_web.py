#!/usr/bin/env python3
"""Pack the management web UI into the firmware as deterministic gzip arrays.

Run from the repository root:

    python3 tools/pack_web.py          # regenerate main/web/web_assets.c
    python3 tools/pack_web.py --check  # fail when the committed file is stale

The gzip header is built manually with a zero mtime and OS=255.  The check
decompresses the committed arrays and compares the payload with the sources, so
a different zlib build cannot turn a content match into a false failure.
"""

import os
import re
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_DIR = os.path.join(ROOT, "main", "web_src")
OUT = os.path.join(ROOT, "main", "web", "web_assets.c")

ASSETS = [
    ("pp_web_index_gz", "index.html"),
    ("pp_web_css_gz", "style.css"),
    ("pp_web_js_gz", "app.js"),
]


def gzip_bytes(data):
    compressor = zlib.compressobj(9, zlib.DEFLATED, -15)
    body = compressor.compress(data) + compressor.flush()
    header = b"\x1f\x8b\x08\x00\x00\x00\x00\x00\x02\xff"
    trailer = (
        zlib.crc32(data) & 0xFFFFFFFF
    ).to_bytes(4, "little") + (len(data) & 0xFFFFFFFF).to_bytes(4, "little")
    return header + body + trailer


def format_array(name, payload):
    lines = ["const uint8_t %s[] = {" % name]
    for offset in range(0, len(payload), 12):
        chunk = payload[offset:offset + 12]
        lines.append("    " + ", ".join("0x%02x" % value for value in chunk) + ",")
    lines.append("};")
    lines.append("const size_t %s_len = sizeof(%s);" % (name, name))
    return "\n".join(lines)


def build():
    parts = [
        "// Generated by tools/pack_web.py -- do not edit by hand.",
        '#include "web/web_assets.h"',
        "",
    ]
    total_raw = 0
    total_gz = 0
    for name, filename in ASSETS:
        path = os.path.join(SRC_DIR, filename)
        with open(path, "rb") as handle:
            raw = handle.read()
        packed = gzip_bytes(raw)
        total_raw += len(raw)
        total_gz += len(packed)
        parts.append("// %s: %d -> %d bytes" % (filename, len(raw), len(packed)))
        parts.append(format_array(name, packed))
        parts.append("")
    parts.append(
        "// total: %d -> %d bytes\n" % (total_raw, total_gz)
    )
    return "\n".join(parts)


def extract_array(source, name):
    match = re.search(r"const uint8_t %s\[\] = \{(.*?)\};" % re.escape(name),
                      source, re.S)
    if not match:
        return None
    values = re.findall(r"0x([0-9a-fA-F]{2})", match.group(1))
    return bytes(int(value, 16) for value in values)


def check_committed():
    try:
        with open(OUT, "r", encoding="utf-8") as handle:
            committed = handle.read()
    except OSError as error:
        print("cannot read %s: %s" % (os.path.relpath(OUT, ROOT), error),
              file=sys.stderr)
        return 1
    ok = True
    for name, filename in ASSETS:
        packed = extract_array(committed, name)
        if packed is None:
            print("missing array: %s" % name, file=sys.stderr)
            ok = False
            continue
        try:
            unpacked = zlib.decompress(packed, 31)
        except zlib.error as error:
            print("cannot decompress %s: %s" % (name, error), file=sys.stderr)
            ok = False
            continue
        with open(os.path.join(SRC_DIR, filename), "rb") as handle:
            source_bytes = handle.read()
        if unpacked != source_bytes:
            print("out of date: %s" % filename, file=sys.stderr)
            ok = False
    if ok:
        print("web assets: up to date")
        return 0
    return 1


def main():
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        return check_committed()
    expected = build()
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(expected)
    print("wrote %s" % os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
