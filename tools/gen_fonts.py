#!/usr/bin/env python3
"""Build the device font subset and its character inventory.

The inventory is:
  * printable ASCII
  * GB2312 symbols and level-1 common characters
  * every non-ASCII character that appears in main/ sources (fixed UI copy)

The source TTF is not committed.  Record its release URL and SHA-256 in
assets/README.md.  Generation is reproducible with a pinned lv_font_conv:

    python3 tools/gen_fonts.py \
        --font /path/to/fusion-pixel-12px-proportional-zh_hans.ttf \
        --tool /path/to/node_modules/.bin/lv_font_conv

Without --tool the script invokes `npx --yes lv_font_conv@1.5.3`.
"""

import argparse
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_DIR = os.path.join(ROOT, "assets", "fonts")
CHARSET_TXT = os.path.join(FONT_DIR, "pp_font_charset.txt")
CHARSET_C = os.path.join(FONT_DIR, "pp_font_charset.c")
SOURCES = ("main",)
SKIP_DIRS = ("main/third_party", "main/web_src")
SKIP_FILES = ("main/web/web_assets.c",)

EXTRA_PUNCTUATION = (
    "　、。【】《》〈〉"
    "，．：；！？（）～／"
    "‘’“”…—·×¥"
    "↑↓←→▲▼"
)


def gb2312_characters():
    characters = set()
    for first, second in ((0xA1, 0xAA), (0xB0, 0xF8)):
        for high in range(first, second):
            for low in range(0xA1, 0xFF):
                try:
                    characters.add(bytes((high, low)).decode("gb2312"))
                except UnicodeDecodeError:
                    continue
    return characters


def source_characters():
    found = set()
    for base in SOURCES:
        for directory, dirnames, filenames in os.walk(os.path.join(ROOT, base)):
            relative_dir = os.path.relpath(directory, ROOT).replace(os.sep, "/")
            if any(relative_dir == skip or relative_dir.startswith(skip + "/")
                   for skip in SKIP_DIRS):
                dirnames[:] = []
                continue
            for filename in filenames:
                if not filename.endswith((".c", ".h")):
                    continue
                relative = os.path.join(directory, filename)
                relative_posix = os.path.relpath(relative, ROOT).replace(os.sep, "/")
                if relative_posix in SKIP_FILES:
                    continue
                try:
                    with open(relative, encoding="utf-8") as handle:
                        text = handle.read()
                except (OSError, UnicodeError):
                    continue
                for character in text:
                    if ord(character) > 0x7E:
                        found.add(character)
    return found


def load_cmap(path):
    try:
        from fontTools.ttLib import TTFont
    except ImportError:
        print("ERROR: fonttools is required for generation (pip install fonttools)",
              file=sys.stderr)
        return None
    font = TTFont(path, lazy=True)
    return set(font.getBestCmap().keys())


def write_charset(characters):
    os.makedirs(FONT_DIR, exist_ok=True)
    lines = [
        "# Player Pass device font character inventory",
        "# Source font: Fusion Pixel 12px proportional zh_hans, release 2026.10.25",
        "# License: SIL Open Font License 1.1",
        "# Inventory: GB2312 symbols + level 1 + level 2 where the font has a glyph,",
        "# Generated by tools/gen_fonts.py; one code point per line.",
    ]
    for codepoint in sorted(characters):
        character = chr(codepoint)
        if codepoint == 0x20:
            character = " "
        lines.append("U+%04X\t%s" % (codepoint, character))
    with open(CHARSET_TXT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")


def write_ranges(characters):
    codepoints = sorted(characters)
    ranges = []
    start = previous = None
    for codepoint in codepoints:
        if start is None:
            start = previous = codepoint
            continue
        if codepoint == previous + 1:
            previous = codepoint
            continue
        ranges.append((start, previous))
        start = previous = codepoint
    if start is not None:
        ranges.append((start, previous))

    lines = [
        "// Generated by tools/gen_fonts.py -- do not edit by hand.",
        '#include "font/pp_font_charset.h"',
        "",
        "const pp_font_range_t pp_font_charset_ranges[] = {",
    ]
    for first, last in ranges:
        lines.append("    { 0x%04X, 0x%04X }," % (first, last))
    lines.append("};")
    lines.append("")
    lines.append("const size_t pp_font_charset_range_count =")
    lines.append("    sizeof(pp_font_charset_ranges) / sizeof(pp_font_charset_ranges[0]);")
    lines.append("")
    with open(CHARSET_C, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))
    return len(ranges)


def patch_line_height(path, line_height):
    with open(path, encoding="utf-8") as handle:
        text = handle.read()
    patched, count = re.subn(r"(\.line_height = )\d+(,)", r"\g<1>%d\g<2>" % line_height,
                             text, count=1)
    if count != 1:
        raise RuntimeError("could not find line_height in %s" % path)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(patched)


def run_tool(tool, font, symbols, size, name, output, line_height):
    command = list(tool) + [
        "--font", font,
        "--symbols", symbols,
        "--size", str(size),
        "--bpp", "1",
        "--format", "lvgl",
        "--no-compress",
        "--lv-font-name", name,
        "--lv-include", "lvgl.h",
        "--output", output,
    ]
    print("generating %s (%d px) ..." % (name, size))
    result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True)
    if result.returncode != 0:
        sys.stderr.write(result.stdout)
        sys.stderr.write(result.stderr)
        raise RuntimeError("lv_font_conv failed for %s" % name)
    if result.stderr.strip():
        print(result.stderr.strip())
    patch_line_height(output, line_height)
    print("  wrote %s" % os.path.relpath(output, ROOT))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", required=True, help="licensed source TTF")
    parser.add_argument("--tool", help="path to pinned lv_font_conv executable")
    args = parser.parse_args()

    if not os.path.isfile(args.font):
        print("ERROR: font not found: %s" % args.font, file=sys.stderr)
        return 1

    cmap = load_cmap(args.font)
    if cmap is None:
        return 1

    requested = set(chr(cp) for cp in range(0x20, 0x7F))
    requested.update(EXTRA_PUNCTUATION)
    requested.update(gb2312_characters())
    source = source_characters()

    missing_source = sorted(set(ord(c) for c in source if ord(c) not in cmap))
    if missing_source:
        print("ERROR: source font lacks UI characters: %s" %
              ", ".join("U+%04X" % cp for cp in missing_source), file=sys.stderr)
        return 1

    requested = set(character for character in requested if ord(character) in cmap)
    # These fullwidth currency signs are not part of the product's text.  Drop
    # the block to keep the inventory focused; dense CJK runs may still use
    # LVGL 9.5's FORMAT0_FULL cmap, which tools/check_fonts.py parses.
    requested = set(character for character in requested
                    if not 0xFFE0 <= ord(character) <= 0xFFE5)
    requested.update(source)
    characters = sorted(requested, key=ord)
    write_charset(set(ord(character) for character in characters))
    range_count = write_ranges(set(ord(character) for character in characters))
    print("charset: %d code points, %d ranges" % (len(characters), range_count))

    tool = [args.tool] if args.tool else ["npx", "--yes", "lv_font_conv@1.5.3"]
    symbols = "".join(characters)
    run_tool(tool, args.font, symbols, 12, "pp_font_12",
             os.path.join(FONT_DIR, "pp_font_12.c"), 16)
    run_tool(tool, args.font, symbols, 24, "pp_font_24",
             os.path.join(FONT_DIR, "pp_font_24.c"), 28)
    return 0


if __name__ == "__main__":
    sys.exit(main())
